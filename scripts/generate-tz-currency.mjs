/**
 * Builds the timezone → currency map from two maintained sources:
 * - countries-and-timezones (IANA zone → ISO country)
 * - Unicode CLDR supplemental currencyData (country → current tender)
 *
 * countries-and-timezones lists the primary country first. Linked zones
 * (Asia/Kuwait → Asia/Riyadh) keep the country on the link.
 * Zones with no country, or whose country has no current tender, are omitted.
 * The app treats a missing zone as USD.
 *
 * Run: node scripts/generate-tz-currency.mjs
 */
import { writeFileSync } from 'node:fs';
import { getAllTimezones } from 'countries-and-timezones';

const CLDR_URL =
  'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/currencyData.json';
const OUT_TZ = new URL('../src/app/core/services/currency/tz-currency.ts', import.meta.url);
const OUT_COUNTRY = new URL('../src/app/core/services/currency/country-currency.ts', import.meta.url);

const response = await fetch(CLDR_URL);
if (!response.ok) {
  throw new Error(`CLDR currency data returned ${response.status}.`);
}
const payload = await response.json();
const regions = payload?.supplemental?.currencyData?.region;
if (!regions || typeof regions !== 'object') {
  throw new Error('CLDR currency data has no region table.');
}

/** @type {Record<string, string>} */
const countryCurrency = {};
for (const [country, entries] of Object.entries(regions)) {
  if (!Array.isArray(entries)) continue;
  const code = currentTender(entries);
  if (code) countryCurrency[country] = code;
}

/** @type {Record<string, string>} */
const map = {};
for (const zone of Object.values(getAllTimezones({ deprecated: true }))) {
  const currency = (zone.countries ?? []).map((country) => countryCurrency[country]).find(Boolean);
  if (currency) map[zone.name] = currency;
}

const lines = Object.keys(map)
  .sort()
  .map((zone) => `  '${zone}': '${map[zone]}',`);

const source = `/* Generated by scripts/generate-tz-currency.mjs. Do not edit.
 * Sources: countries-and-timezones, Unicode CLDR currencyData.
 * ${Object.keys(map).length} zones. A zone missing from this map falls back to USD.
 */
export const TZ_CURRENCY: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;

writeFileSync(OUT_TZ, source);
console.log(`Wrote ${Object.keys(map).length} zones.`);

const countryLines = Object.keys(countryCurrency)
  .sort()
  .map((country) => `  '${country}': '${countryCurrency[country]}',`);

const countrySource = `/* Generated by scripts/generate-tz-currency.mjs. Do not edit.
 * Source: Unicode CLDR currencyData (ISO country → tender).
 * ${Object.keys(countryCurrency).length} countries. Missing country falls back to USD in currencyFromCountry().
 */
export const COUNTRY_CURRENCY: Readonly<Record<string, string>> = {
${countryLines.join('\n')}
};
`;

writeFileSync(OUT_COUNTRY, countrySource);
console.log(`Wrote ${Object.keys(countryCurrency).length} countries.`);
for (const zone of [
  'Africa/Cairo',
  'Asia/Riyadh',
  'Asia/Kuwait',
  'Asia/Dubai',
  'Asia/Muscat',
  'Asia/Qatar',
  'Asia/Bahrain',
  'Europe/Paris',
  'America/New_York',
  'Asia/Beirut',
  'Europe/Istanbul',
  'America/Toronto',
  'Asia/Tokyo',
  'Europe/London',
]) {
  console.log(zone, map[zone] ?? '(omitted)');
}

/**
 * @param {Array<Record<string, { _from?: string, _to?: string, _tender?: string }>>} entries
 */
function currentTender(entries) {
  /** @type {{ code: string, from: string }[]} */
  const current = [];
  for (const item of entries) {
    const code = Object.keys(item)[0];
    if (!code) continue;
    const meta = item[code] ?? {};
    if (meta._tender === 'false' || meta._to) continue;
    current.push({ code, from: meta._from ?? '' });
  }
  current.sort((a, b) => (a.from < b.from ? 1 : a.from > b.from ? -1 : 0));
  return current[0]?.code ?? null;
}
